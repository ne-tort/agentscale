"""Публичный API слоя capability-адаптеров плагинов (F2).

Всё, что нужно задачам 04 (HTTP surface) и F11 (интеграция родителем):

* ``PluginCapabilityService.invoke(...)`` / ``authorize(...)`` — точка входа;
* ``AdapterRegistry`` + ``AdapterMissingError``/``UnknownCapabilityError`` —
  fail-closed разрешение адаптеров;
* ``InMemoryQuota``/``PluginQuota``/``PluginQuotaKey`` — квоты per-
  ``(company, instance, digest)``;
* ``InMemoryAudit``/``PluginAuditEvent``/``redact`` — append-only аудит;
* ``CapabilityEnvelope`` и typed Request/Response из ``contracts``;
* совместимые имена исключений для HTTP-маппинга задачи 04.

Ядро ``CapabilityGatewayService`` импортируется и вызывается, НО не
редактируется и не копируется. ``db.direct`` здесь отсутствует: БД плагина —
прямой DSN к своей БД компании (§4.3, ADR-007).
"""

